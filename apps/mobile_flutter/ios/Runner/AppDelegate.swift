// Note: iOS notification support is configured via flutter_local_notifications plugin.
// The plugin automatically requests notification permissions when initialized in main().
// Timezone data is automatically bundled for scheduling recurring notifications.

@main
@objc class AppDelegate: FlutterAppDelegate, FlutterImplicitEngineDelegate {
